def simp_to_trad_text(text):
    """将简体中文文本转换为繁体中文"""
    result = []
    for char in text:
        result.append(SIMP_TO_TRAD_MAP.get(char, char))
    return ''.join(result)

def fix_traditional_file(simp_file, trad_file):
    """修复繁体中文文件"""
    if not os.path.exists(simp_file):
        print(f'简体文件不存在: {simp_file}')
        return False
    
    # 读取简体文件
    with open(simp_file, 'r', encoding='utf-8') as f:
        content = f.read()
    
    # 解析并转换
    lines = content.split('\n')
    new_lines = []
    
    for line in lines:
        if '=' in line and line.strip().startswith('"'):
            # 解析 "简体key"="简体value"
            match = re.match(r'^(".*?")=(.*?);$', line.strip())
            if match:
                key = match.group(1)  # 键保持简体
                value_part = match.group(2).strip()
                
                # 提取值（去掉引号）
                if value_part.startswith('"') and value_part.endswith('"'):
                    simp_value = value_part[1:-1]
                    # 转换为繁体
                    trad_value = simp_to_trad_text(simp_value)
                    new_lines.append(f'{key}="{trad_value}";')
                else:
                    new_lines.append(line)
            else:
                new_lines.append(line)
        else:
            new_lines.append(line)
    
    # 写入目标文件
    with open(trad_file, 'w', encoding='utf-8') as f:
        f.write('\n'.join(new_lines))
    
    return True

